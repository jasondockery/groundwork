#!/usr/bin/env node
// Generates thin .claude/skills and .agents/skills discovery adapters for
// Groundwork-local skills — the ones under skills/ that Compass does not
// manage and therefore does not project an adapter for. Compass-managed
// skills already get their adapters from the projected artifact; this script
// covers only the remainder, so every skill under skills/ stays natively
// discoverable by every tool, matching the guarantee the old blanket
// `.agents/skills -> ../skills` symlink used to give for free before
// Compass's materialized-adapter route transition.
import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

import { COMPASS_SKILL_NAMES } from '../.compass/check-projection.mjs'

const ADAPTER_DIRS = ['.claude/skills', '.agents/skills']
const GENERATED_BANNER = 'GENERATED by scripts/generate-skill-adapters.mjs — do not edit.'
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

function unquote(value) {
  const trimmed = value.trim()
  if (
    trimmed.length >= 2 &&
    ((trimmed.startsWith("'") && trimmed.endsWith("'")) ||
      (trimmed.startsWith('"') && trimmed.endsWith('"')))
  ) {
    return trimmed.slice(1, -1)
  }
  return trimmed
}

function parseSkillDocument(markdown) {
  const frontmatter = /^---\n([\s\S]*?)\n---(?:\n|$)/.exec(markdown)?.[1]
  if (frontmatter === undefined) return undefined
  const name = /^name:\s*(.+)$/m.exec(frontmatter)?.[1]
  const description = /^description:\s*(.+)$/m.exec(frontmatter)?.[1]
  if (name === undefined || description === undefined) return undefined
  const heading = /^#\s+(.+)$/m.exec(markdown.slice(frontmatter.length + 8))?.[1]?.trim()
  return {
    name: unquote(name),
    title: heading || unquote(name),
    description: unquote(description).replace(/\s+/g, ' ').trim(),
  }
}

function renderSkillAdapter(name, parsed) {
  const description = parsed.description.replaceAll('"', "'")
  return [
    '---',
    `name: ${name}`,
    `description: "${description}"`,
    '---',
    '',
    `# ${parsed.title}`,
    '',
    `> ${GENERATED_BANNER}`,
    '',
    `**Canonical workflow: [\`skills/${name}/SKILL.md\`](../../../skills/${name}/SKILL.md).**`,
    '',
    'Read that file and follow it. This adapter exists only so the skill is',
    'discovered natively by this tool; the workflow itself is maintained in one',
    'place so the two trees cannot drift apart.',
    '',
  ].join('\n')
}

function localSkillNames() {
  return fs
    .readdirSync(path.join(root, 'skills'), { withFileTypes: true })
    .filter(
      (entry) =>
        entry.isDirectory() &&
        !COMPASS_SKILL_NAMES.includes(entry.name) &&
        fs.existsSync(path.join(root, 'skills', entry.name, 'SKILL.md'))
    )
    .map((entry) => entry.name)
    .sort()
}

export function generatedLocalSkillAdapters() {
  const adapters = []
  for (const name of localSkillNames()) {
    const source = fs.readFileSync(path.join(root, 'skills', name, 'SKILL.md'), 'utf8')
    const parsed = parseSkillDocument(source)
    if (parsed === undefined) throw new Error(`skills/${name}/SKILL.md has invalid skill metadata`)
    if (parsed.name !== undefined && parsed.name !== name) {
      throw new Error(`skills/${name}/SKILL.md skill name must equal directory ${name}`)
    }
    const contents = renderSkillAdapter(name, parsed)
    for (const directory of ADAPTER_DIRS) {
      adapters.push({ relativePath: `${directory}/${name}/SKILL.md`, contents })
    }
  }
  return adapters
}

function isMainModule() {
  try {
    return fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url))
  } catch {
    return false
  }
}

if (isMainModule()) {
  const checkOnly = process.argv.includes('--check')
  const problems = []
  const written = []
  for (const adapter of generatedLocalSkillAdapters()) {
    const target = path.join(root, ...adapter.relativePath.split('/'))
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : undefined
    if (current === adapter.contents) continue
    if (checkOnly) {
      problems.push(adapter.relativePath)
      continue
    }
    fs.mkdirSync(path.dirname(target), { recursive: true })
    fs.writeFileSync(target, adapter.contents)
    written.push(adapter.relativePath)
  }
  if (checkOnly && problems.length > 0) {
    console.error(
      `Local skill discovery adapters are stale or missing:\n- ${problems.join('\n- ')}\nRun: node scripts/generate-skill-adapters.mjs`
    )
    process.exitCode = 1
  } else if (!checkOnly) {
    console.log(
      written.length > 0
        ? `Wrote ${written.length} local skill discovery adapter(s):\n- ${written.join('\n- ')}`
        : 'Local skill discovery adapters are already current.'
    )
  }
}
